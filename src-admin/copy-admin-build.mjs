import {
cp,
mkdir,
readdir,
rm,
stat,
} from "node:fs/promises";

import {
basename,
dirname,
join,
resolve,
} from "node:path";

import {
fileURLToPath,
} from "node:url";

const scriptDirectory =
dirname(
fileURLToPath(
import.meta.url,
),
);

const buildDirectory =
resolve(
scriptDirectory,
"build",
);

const adminDirectory =
resolve(
scriptDirectory,
"..",
"admin",
);

async function exists(
path,
) {
try {
await stat(path);
return true;
} catch {
return false;
}
}

async function copyEntry(
source,
target,
) {
await cp(
source,
target,
{
recursive: true,
force: true,
},
);
}

if (!(await exists(buildDirectory))) {
throw new Error(
`React build directory does not exist: ${buildDirectory}`,
);
}

const indexSource =
join(
buildDirectory,
"index.html",
);

if (!(await exists(indexSource))) {
throw new Error(
`React index file does not exist: ${indexSource}`,
);
}

await mkdir(
adminDirectory,
{
recursive: true,
},
);

/*
 * Remove only files generated by the previous React build.
 * Adapter assets, translations, jsonConfig.json and icons remain intact.
 */
for (const generatedEntry of [
"index_m.html",
"asset-manifest.json",
"manifest.json",
"robots.txt",
"static",
]) {
const target =
join(
adminDirectory,
generatedEntry,
);

await rm(
target,
{
recursive: true,
force: true,
},
);
}

const entries =
await readdir(
buildDirectory,
{
withFileTypes: true,
},
);

for (const entry of entries) {
const source =
join(
buildDirectory,
entry.name,
);

const targetName =
entry.name === "index.html"
? "index_m.html"
: entry.name;

const target =
join(
adminDirectory,
targetName,
);

await copyEntry(
source,
target,
);

console.log(
`Copied ${basename(source)} -> ${basename(target)}`,
);
}

console.log(
`React Admin copied to ${adminDirectory}`,
);
